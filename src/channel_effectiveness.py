"""
Channel Effectiveness & ROAS Analysis
------------------------------------
Run from the repository root:
    python -m src.channel_effectiveness

Uses existing MMM outputs. Does NOT retrain or modify the MMM.
Outputs:
    outputs/channel_analysis/*.csv
    reports/figures/channel_*.png
    reports/channel_effectiveness_roi.md
"""
from pathlib import Path
import json
import warnings

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from src.mmm_response import ResponseModel, LABELS

warnings.filterwarnings("ignore", category=FutureWarning)

ROOT = Path(__file__).resolve().parents[1]
MMM_OUT = ROOT / "outputs" / "mmm"
MODEL_DIR = ROOT / "models" / "mmm"
OUT_DIR = ROOT / "outputs" / "channel_analysis"
FIG_DIR = ROOT / "reports" / "figures"
REPORT_DIR = ROOT / "reports"

for folder in (OUT_DIR, FIG_DIR, REPORT_DIR):
    folder.mkdir(parents=True, exist_ok=True)

SUMMARY_PATH = MMM_OUT / "channel_summary.csv"
CURVES_PATH = MMM_OUT / "response_curves.csv"
BOOT_PATH = MMM_OUT / "roas_bootstrap.csv"
MODEL_PATH = MODEL_DIR / "final_mmm.json"

required = [SUMMARY_PATH, CURVES_PATH, BOOT_PATH, MODEL_PATH]
missing = [str(p.relative_to(ROOT)) for p in required if not p.exists()]
if missing:
    raise FileNotFoundError(
        "Required MMM outputs are missing:\n- " + "\n- ".join(missing)
        + "\nRun notebook 08 first, then rerun this script."
    )

# ---------------------------------------------------------------------
# 1. Load the model outputs generated by the MMM team
# ---------------------------------------------------------------------
summary = pd.read_csv(SUMMARY_PATH, index_col=0)
curves = pd.read_csv(CURVES_PATH)
bootstrap = pd.read_csv(BOOT_PATH, index_col=0)
response_model = ResponseModel(MODEL_PATH)

# Standardise index labels and retain only channels known to the model.
summary.index = summary.index.astype(str)
bootstrap.index = bootstrap.index.astype(str)
channels = [LABELS[c] for c in response_model.channels]
summary = summary.loc[channels].copy()
bootstrap = bootstrap.reindex(channels)

# ---------------------------------------------------------------------
# 2. Channel contribution, ROAS and efficiency ranking
# ---------------------------------------------------------------------
performance = summary.copy()

# Contribution efficiency index > 1 means the channel's contribution
# share is larger than its share of total advertising expenditure.
performance["contribution_to_spend_index"] = (
    performance["contribution_share_pct"] /
    performance["spend_share_pct"].replace(0, np.nan)
)

performance["roas_rank"] = performance["roas"].rank(
    ascending=False, method="min"
).astype(int)
performance["marginal_roas_rank"] = performance[
    "marginal_roas_at_current"
].rank(ascending=False, method="min").astype(int)

performance["roas_p05"] = bootstrap["roas_p05"]
performance["roas_median_bootstrap"] = bootstrap["roas_median"]
performance["roas_p95"] = bootstrap["roas_p95"]
performance["prob_roas_gt_1"] = bootstrap["prob_roas_gt_1"]
performance["prob_effect_zero"] = bootstrap["prob_effect_zero"]

performance["roas_interval_width"] = (
    performance["roas_p95"] - performance["roas_p05"]
)

performance = performance.sort_values("roas", ascending=False)
performance.to_csv(OUT_DIR / "channel_performance.csv", float_format="%.6f")

# ---------------------------------------------------------------------
# 3. Diminishing returns: evaluate each channel at current, 1.5x and 2x
# ---------------------------------------------------------------------
diminishing_rows = []
for channel_code in response_model.channels:
    label = LABELS[channel_code]
    current = float(summary.loc[label, "current_monthly_spend_lkr"])
    spend_levels = {
        "current": current,
        "1_25x_current": current * 1.25,
        "1_5x_current": current * 1.50,
        "2x_current": current * 2.00,
    }

    row = {
        "channel": label,
        "current_monthly_spend_lkr": current,
    }
    for scenario, spend in spend_levels.items():
        row[f"{scenario}_incremental_revenue_lkr"] = float(
            response_model.response(channel_code, spend)
        )
        row[f"{scenario}_marginal_roas"] = float(
            response_model.marginal_roas(channel_code, spend)
        )
        row[f"{scenario}_average_roas"] = float(
            response_model.average_roas(channel_code, spend)
        )

    current_mroas = row["current_marginal_roas"]
    mroas_1_5 = row["1_5x_current_marginal_roas"]
    row["marginal_roas_decline_at_1_5x_pct"] = (
        (current_mroas - mroas_1_5) / current_mroas * 100
        if current_mroas > 0 else np.nan
    )
    row["additional_revenue_from_current_to_1_5x_lkr"] = (
        row["1_5x_current_incremental_revenue_lkr"]
        - row["current_incremental_revenue_lkr"]
    )
    diminishing_rows.append(row)

diminishing = pd.DataFrame(diminishing_rows).set_index("channel")
diminishing.to_csv(
    OUT_DIR / "diminishing_returns_analysis.csv", float_format="%.6f"
)

# ---------------------------------------------------------------------
# 4. Evidence-based recommendations (rules are transparent, not causal proof)
# ---------------------------------------------------------------------
recommendation_rows = []
for channel in channels:
    r = performance.loc[channel]
    mroas = float(r["marginal_roas_at_current"])
    roas = float(r["roas"])
    prob = float(r["prob_roas_gt_1"])
    p_zero = float(r["prob_effect_zero"])

    if p_zero >= 0.25:
        action = "Investigate before reallocating"
        reason = (
            "The bootstrap assigns meaningful probability to a zero effect; "
            "check data quality, channel activity and model uncertainty."
        )
    elif roas > 1 and mroas > 1 and prob >= 0.80:
        action = "Consider gradual testing of additional spend"
        reason = (
            "Average and marginal revenue returns are above 1, with relatively "
            "strong bootstrap support. Increase in controlled steps and monitor."
        )
    elif mroas < 1 and roas < 1:
        action = "Review and consider reducing or reallocating spend"
        reason = (
            "Both average and next-LKR revenue returns are below 1. Validate "
            "business objectives and uncertainty before reducing."
        )
    elif mroas > 1:
        action = "Potential for cautious additional investment"
        reason = (
            "The marginal revenue return is above 1; response curves should be "
            "checked for the point at which returns decline."
        )
    else:
        action = "Maintain or test a revised allocation"
        reason = (
            "The evidence is mixed. Compare alternative spend levels and "
            "validate performance in future periods."
        )

    recommendation_rows.append({
        "channel": channel,
        "roas": roas,
        "marginal_roas_at_current": mroas,
        "prob_roas_gt_1": prob,
        "prob_effect_zero": p_zero,
        "suggested_action": action,
        "evidence_and_reason": reason,
    })

recommendations = pd.DataFrame(recommendation_rows).sort_values(
    "roas", ascending=False
)
recommendations.to_csv(
    OUT_DIR / "channel_recommendations.csv", index=False
)

# ---------------------------------------------------------------------
# 5. Visualisation 1: ROAS point estimates with 90% bootstrap intervals
# ---------------------------------------------------------------------
plot_df = performance.sort_values("roas")
fig, ax = plt.subplots(figsize=(9, 5))
y = np.arange(len(plot_df))
x = plot_df["roas"].to_numpy()
lower = np.maximum(0, x - plot_df["roas_p05"].to_numpy())
upper = np.maximum(0, plot_df["roas_p95"].to_numpy() - x)
ax.errorbar(
    x, y, xerr=np.vstack([lower, upper]), fmt="o",
    capsize=4, linewidth=2
)
ax.axvline(1, linestyle="--", linewidth=1, label="ROAS = 1")
ax.set_yticks(y, plot_df.index)
ax.set_xlabel("Incremental revenue per LKR of advertising spend")
ax.set_title("Channel ROAS with 90% bootstrap intervals")
ax.grid(axis="x", alpha=0.25)
ax.legend()
fig.tight_layout()
fig.savefig(FIG_DIR / "channel_roas_with_uncertainty.png", dpi=180)
plt.close(fig)

# ---------------------------------------------------------------------
# 6. Visualisation 2: share of spend vs share of media contribution
# ---------------------------------------------------------------------
plot_df = performance.sort_values("contribution_share_pct")
fig, ax = plt.subplots(figsize=(9, 5))
y = np.arange(len(plot_df))
h = 0.36
ax.barh(y - h/2, plot_df["spend_share_pct"], height=h, label="Spend share (%)")
ax.barh(
    y + h/2, plot_df["contribution_share_pct"],
    height=h, label="Media contribution share (%)"
)
ax.set_yticks(y, plot_df.index)
ax.set_xlabel("Share (%)")
ax.set_title("Advertising spend share vs media contribution share")
ax.legend()
ax.grid(axis="x", alpha=0.25)
fig.tight_layout()
fig.savefig(FIG_DIR / "channel_spend_vs_contribution.png", dpi=180)
plt.close(fig)

# ---------------------------------------------------------------------
# 7. Visualisation 3: response curves and marginal ROAS
# ---------------------------------------------------------------------
fig, axes = plt.subplots(2, 3, figsize=(14, 8))
for ax, channel_code in zip(axes.flat, response_model.channels):
    label = LABELS[channel_code]
    d = curves[curves["channel"] == label].sort_values("monthly_spend_lkr")
    current = float(summary.loc[label, "current_monthly_spend_lkr"])

    ax.plot(
        d["monthly_spend_lkr"] / 1e6,
        d["incremental_revenue_lkr"] / 1e6,
        label="Incremental revenue"
    )
    ax.axvline(current / 1e6, linestyle=":", linewidth=1.5,
               label="Current spend")
    ax.set_title(label)
    ax.set_xlabel("Monthly spend (LKR millions)")
    ax.set_ylabel("Monthly incremental revenue (LKR millions)")
    ax.grid(alpha=0.25)
    ax.legend(fontsize=8)

fig.suptitle("MMM response curves: diminishing returns by channel")
fig.tight_layout()
fig.savefig(FIG_DIR / "channel_diminishing_returns.png", dpi=180)
plt.close(fig)

# ---------------------------------------------------------------------
# 8. Visualisation 4: marginal ROAS at current spend and at 1.5x spend
# ---------------------------------------------------------------------
plot_mr = diminishing[
    ["current_marginal_roas", "1_5x_current_marginal_roas"]
].copy()
fig, ax = plt.subplots(figsize=(9, 5))
y = np.arange(len(plot_mr))
h = 0.36
ax.barh(y - h/2, plot_mr["current_marginal_roas"], height=h,
        label="Current spend")
ax.barh(y + h/2, plot_mr["1_5x_current_marginal_roas"], height=h,
        label="1.5x current spend")
ax.axvline(1, linestyle="--", linewidth=1, label="Marginal ROAS = 1")
ax.set_yticks(y, plot_mr.index)
ax.set_xlabel("Marginal ROAS")
ax.set_title("Marginal ROAS as advertising spend increases")
ax.legend()
ax.grid(axis="x", alpha=0.25)
fig.tight_layout()
fig.savefig(FIG_DIR / "channel_marginal_roas_scenarios.png", dpi=180)
plt.close(fig)

# ---------------------------------------------------------------------
# 9. Write a concise report using the actual output values
# ---------------------------------------------------------------------
best = performance["roas"].idxmax()
lowest = performance["roas"].idxmin()
best_marginal = performance["marginal_roas_at_current"].idxmax()

lines = [
    "# Channel Effectiveness & ROAS Analysis",
    "",
    "## Scope and method",
    "",
    "This analysis reuses the fitted Marketing Mix Model and its saved outputs. "
    "It does not retrain or alter the MMM. Channel contribution is taken from "
    "`channel_summary.csv`; ROAS is incremental revenue divided by advertising "
    "spend. Marginal ROAS and response curves are evaluated using the saved "
    "response model. Bootstrap intervals are taken from the moving-block "
    "bootstrap output generated in Notebook 08.",
    "",
    "## Important financial limitation",
    "",
    "The dataset does not provide channel-level profit margins or incremental "
    "profit. Therefore, this report uses revenue-based ROAS and does not claim "
    "to calculate profit ROI. ROAS above 1 means estimated incremental revenue "
    "exceeds ad spend, not necessarily that the channel is profitable after "
    "product, fulfilment and other costs.",
    "",
    "## Channel comparison",
    "",
    "| Channel | Spend (LKR) | Incremental revenue (LKR) | ROAS | Marginal ROAS | ROAS 90% interval |",
    "|---|---:|---:|---:|---:|---:|",
]
for channel, r in performance.iterrows():
    lines.append(
        f"| {channel} | {r['total_spend_lkr']:,.0f} | "
        f"{r['incremental_revenue_lkr']:,.0f} | {r['roas']:.2f} | "
        f"{r['marginal_roas_at_current']:.2f} | "
        f"{r['roas_p05']:.2f}–{r['roas_p95']:.2f} |"
    )

lines += [
    "",
    "## Key findings",
    "",
    f"- Highest point-estimate ROAS: **{best}** "
    f"({performance.loc[best, 'roas']:.2f}).",
    f"- Lowest point-estimate ROAS: **{lowest}** "
    f"({performance.loc[lowest, 'roas']:.2f}).",
    f"- Highest marginal ROAS at current spend: **{best_marginal}** "
    f"({performance.loc[best_marginal, 'marginal_roas_at_current']:.2f}).",
    "- ROAS is an average return over the observed period; marginal ROAS "
    "estimates the return from the next unit of spend. They answer different questions.",
    "- The response curves show the modelled change in incremental monthly "
    "revenue as sustained monthly spend changes. A declining slope indicates "
    "diminishing marginal returns.",
    "",
    "## Recommendations",
    "",
]
for _, r in recommendations.iterrows():
    lines.append(
        f"- **{r['channel']} — {r['suggested_action']}.** "
        f"{r['evidence_and_reason']} "
        f"Point ROAS = {r['roas']:.2f}; marginal ROAS = "
        f"{r['marginal_roas_at_current']:.2f}; bootstrap probability "
        f"ROAS > 1 = {r['prob_roas_gt_1']:.1%}."
    )

lines += [
    "",
    "## Limitations",
    "",
    "- The analysis is conditional on the fitted MMM specification and available data.",
    "- The project has 36 monthly observations, so estimates and bootstrap intervals "
    "should be interpreted cautiously.",
    "- Bootstrap intervals quantify uncertainty under the notebook's resampling "
    "procedure and fixed model settings; they do not capture every source of model uncertainty.",
    "- A modelled channel contribution is an attribution estimate, not proof of causation.",
    "- Budget changes should be tested gradually and monitored against future actual outcomes.",
    "",
    "## Generated files",
    "",
    "- `outputs/channel_analysis/channel_performance.csv`",
    "- `outputs/channel_analysis/diminishing_returns_analysis.csv`",
    "- `outputs/channel_analysis/channel_recommendations.csv`",
    "- `reports/figures/channel_roas_with_uncertainty.png`",
    "- `reports/figures/channel_spend_vs_contribution.png`",
    "- `reports/figures/channel_diminishing_returns.png`",
    "- `reports/figures/channel_marginal_roas_scenarios.png`",
]
(REPORT_DIR / "channel_effectiveness_roi.md").write_text(
    "\n".join(lines), encoding="utf-8"
)

print("Channel effectiveness analysis completed.")
print(f"Best ROAS channel: {best} ({performance.loc[best, 'roas']:.2f})")
print(f"Best marginal ROAS channel: {best_marginal} "
      f"({performance.loc[best_marginal, 'marginal_roas_at_current']:.2f})")
print(f"Outputs saved to: {OUT_DIR.relative_to(ROOT)}")
print(f"Report saved to: {(REPORT_DIR / 'channel_effectiveness_roi.md').relative_to(ROOT)}")
